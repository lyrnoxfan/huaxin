#!/usr/bin/env python3
"""Deploy the lyrnox.com `home` Worker via Cloudflare API (multipart script upload).

Usage: deploy-home.py --account ID [--dry-run]
Deploys ./worker.js (generated by gen.py) to the `home` service.
Auth: authd surrogate for custom.cloudflare (local) or CLOUDFLARE_API_TOKEN env.
"""
import sys, json, uuid, urllib.request, os, argparse

sys.path.insert(0, "/opt/hatch/skills/skill-creator/bin")
try:
    from dynamic_credentials import add_surrogate_to_request, DynamicCredentialError
    HAS_SURROGATE = True
except ImportError:
    HAS_SURROGATE = False

API = "https://api.cloudflare.com"
CRED = "custom.cloudflare"
SCRIPT_NAME = "home"


def api(method, path, body=None, content_type="application/json"):
    url = API + path
    req = urllib.request.Request(url, data=body, method=method)
    if content_type and body is not None:
        req.add_header("Content-Type", content_type)
    token = os.environ.get("CLOUDFLARE_API_TOKEN")
    if token:
        req.add_header("Authorization", "Bearer " + token)
    elif HAS_SURROGATE:
        try:
            add_surrogate_to_request(req, CRED, allowed_hosts=("api.cloudflare.com",))
        except DynamicCredentialError as e:
            print("credential error:", e, file=sys.stderr)
            sys.exit(2)
    else:
        print("no credential: set CLOUDFLARE_API_TOKEN", file=sys.stderr)
        sys.exit(2)
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return resp.status, resp.read().decode()
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--account", required=True)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    with open("worker.js", encoding="utf-8") as f:
        script = f.read()

    metadata = {"main_module": "worker.js", "compatibility_date": "2026-10-01"}
    boundary = "----home" + uuid.uuid4().hex
    parts = []

    def add_part(name, filename, ctype, content):
        parts.append(("--%s\r\n" % boundary).encode())
        disp = 'Content-Disposition: form-data; name="%s"' % name
        if filename:
            disp += '; filename="%s"' % filename
        parts.append((disp + "\r\n").encode())
        parts.append(("Content-Type: %s\r\n\r\n" % ctype).encode())
        parts.append(content.encode() if isinstance(content, str) else content)
        parts.append(b"\r\n")

    add_part("metadata", None, "application/json", json.dumps(metadata))
    add_part("script", "worker.js", "application/javascript+module", script)
    body = b"".join(parts) + ("--%s--\r\n" % boundary).encode()

    if a.dry_run:
        print(f"dry-run: would PUT {len(body)} bytes to /workers/scripts/{SCRIPT_NAME}")
        return 0

    status, text = api(
        "PUT", f"/client/v4/accounts/{a.account}/workers/scripts/{SCRIPT_NAME}",
        body, f"multipart/form-data; boundary={boundary}",
    )
    try:
        d = json.loads(text)
    except Exception:
        print(f"HTTP {status}: {text[:500]}")
        return 1
    if d.get("success"):
        print(f"deployed {SCRIPT_NAME}: id={d['result'].get('id')}")
        return 0
    print(f"deploy failed HTTP {status}: {json.dumps(d.get('errors'), ensure_ascii=False)[:500]}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
